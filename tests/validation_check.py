"""Server on localhost:8001 with matching ALLOWED_ORIGINS required."""
from playwright.sync_api import sync_playwright, expect
with sync_playwright() as p:
    browser=p.chromium.launch(args=['--no-sandbox'])
    page=browser.new_page()
    page.goto('http://localhost:8001')
    page.locator('#nick').fill('Alice')
    for value in ['','a1','abcde','12345']:
        page.locator('#pass').fill(value)
        page.locator('#join-button').click()
        expect(page.locator('#join-error')).to_be_visible()
        expect(page.locator('#join-error')).to_contain_text('au moins 5')
        expect(page.locator('#pass')).to_have_attribute('aria-invalid','true')
        expect(page.locator('#pass')).to_be_focused()
    page.locator('#lang').click()
    expect(page.locator('#join-error')).to_contain_text('Invalid passphrase')
    page.locator('#theme').click()
    assert page.locator('#join-error').evaluate('e=>getComputedStyle(e).color')=='rgb(255, 173, 183)'
    page.emulate_media(reduced_motion='reduce')
    page.locator('#join-button').click()
    expect(page.locator('#join')).to_have_css('animation-name','none')
    page.locator('#pass').fill('abcd1')
    expect(page.locator('#join-error')).to_be_hidden()
    page.locator('#join-button').click()
    expect(page.locator('#connection')).to_contain_text('Connected')
    page.locator('#leave').click()
    page.locator('#nick').fill('bad name')
    page.locator('#join-button').click()
    expect(page.locator('#join-error')).to_contain_text('Invalid nickname')
    browser.close()
print('PASS: invalid phrases, visible FR/EN error, focus, red dark theme, reduced motion, correction, valid join, invalid nickname')
